// POST /gemini/generate-flashcards w/ HTTP 400 validation
geminiRouter.post("/generate-flashcards", (req, res) => {
    const {notes} = req.body ?? {};

    // validation: return HTTP 400 bad request if notes input is empty or invalid
    if (!notes || typeof notes !== "string" || notes.trim() === "") {
        return res.status(400).json({
            error: "Bad Request - Missing or invalid study notes/topic input."
        });
    }
    // return meaningful JSON flashcard data for Phase II prototype
    try {
        const generatedCards = [
                {
                    card_id: Date.now() + 1,
                    question: `Generated Q1 based on: "${notes.trim().substring(0, 30)}..."`,
                    answer: "Sample backend generated answer for active recall study.",
                    mastery_score: 0
                }
            ];
        return res.status(200).json({
            message: "Flashcards successfully generated by Express backend",
            cards: generatedCards
        });
    } catch (err) {
        return res.status(500).json({error: "Internal Server Error during AI generation."});

    }
});

geminiRouter.get("/low-mastery", (req, res) => {
    return res.status(200).json({cards: []});
});

export default geminiRouter;
